-- JP client 7.0.0 master schema (Haruki-Sekai-API feat/jp-700-master-schema).
--
-- Target: the master database the ingester writes (CN08 PostgreSQL, database
-- haruki_sekai). Ingest runs with create_tables: false there, and a schema_info.json
-- table missing from the database aborts the whole region's prepare, so this must be
-- applied BEFORE master_ingest is deployed with the new schema_info.json.
--
-- Idempotent: every statement is IF NOT EXISTS, so re-running is a no-op. Additive
-- only: no existing column, type or index changes. New columns stay NULL for regions
-- (and older rows) that do not ship the field.
--
-- Shape matches what Haruki-Cloud's ent migration creates for the generated schemas in
-- ent_schemas/generated/ (identity bigint id, character varying strings, jsonb nested
-- values, NOT NULL server_region, unique index <schema>_game_id_server_region), so a
-- later ent auto-migrate sees nothing to change.
--
-- Run as a role that can SET ROLE haruki_sekai (tables must be owned by haruki_sekai):
--   psql "$DSN" -v ON_ERROR_STOP=1 -f docs/migrations/2026-09-30-jp-700.sql
-- Preflight: the existing tables altered below must already be owned by haruki_sekai:
--   SELECT tablename, tableowner FROM pg_tables WHERE schemaname = 'public'
--     AND tablename IN ('areas','honorgroups','materials','mysekaigates',
--                       'mysekaisiteharvestfixtures','virtuallives');

SET ROLE haruki_sekai;

