ALTER TABLE materials ADD COLUMN IF NOT EXISTS expired_at bigint;
ALTER TABLE mysekaigates ADD COLUMN IF NOT EXISTS mysekai_gate_type character varying;
ALTER TABLE mysekaisiteharvestfixtures ADD COLUMN IF NOT EXISTS mysekai_site_bulk_harvest_target_id bigint;
ALTER TABLE virtuallives ADD COLUMN IF NOT EXISTS virtual_live_total_cheer_point_rewards jsonb;
ALTER TABLE virtuallives ADD COLUMN IF NOT EXISTS virtual_live_total_cheer_point_surplus_reward jsonb;
ALTER TABLE virtuallives ADD COLUMN IF NOT EXISTS virtual_live_virtual_item_override_cost jsonb;

