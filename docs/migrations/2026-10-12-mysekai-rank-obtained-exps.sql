-- Apply to the haruki_sekai master database BEFORE deploying the updated master_ingest.
-- Inspect existing table owners first; create the table as haruki_sekai.
-- The source file exists in all five regions with one row each.
SET ROLE haruki_sekai;
BEGIN;
CREATE TABLE IF NOT EXISTS mysekairankobtainedexps (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id bigint,
    mysekai_rank_obtained_exp_type character varying,
    quantity bigint,
    server_region character varying NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS mysekairankobtainedexp_game_id_server_region
    ON mysekairankobtainedexps (game_id, server_region);
COMMIT;
RESET ROLE;
